/**
 * 클리어 판정 — 3종 공통. 시련별 if 분기가 하나도 없다.
 * 이 함수가 늘어나면 시련 선택이 틀린 것이다.
 */
export function trialProgress(
  t: TrialDef,
  elapsedSec: number,
  kills: number,
  bossKills: number,
): number {
  return elapsedSec * t.wTime + kills * t.wKill + bossKills * t.wBossKill;
}

