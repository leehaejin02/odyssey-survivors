/** 레벨 n → n+1 요구 XP. BASE * GROWTH^(n-1) 반올림. */
export function xpToNextLevel(level: number): number {
  return Math.round(XP_CURVE.BASE * Math.pow(XP_CURVE.GROWTH, level - 1));
}

